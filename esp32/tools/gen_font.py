ORDER = "".join(GLYPHS.keys())
ROWS = 7
COLS = 5


def to_bytes(rows):
    """列优先：每列一个字节，bit0 是最上面一行。"""
    out = []
    for c in range(COLS):
        v = 0
        for r in range(ROWS):
            if rows[r][c] == "#":
                v |= 1 << r
        out.append(v)
    return out


def write_header(path):
    lines = [
        "/* 自动生成，勿手改：python3 tools/gen_font.py */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "#define UI_FONT_W 5",
        "#define UI_FONT_H 7",
        "#define UI_FONT_ADV 6",
        '#define UI_FONT_FIRST \'%s\'' % ORDER[0],
        '#define UI_FONT_LAST  \'%s\'' % ORDER[-1],
        "",
        "static const uint8_t ui_font_chars[] = \"%s\";" % ORDER.replace("\\", "\\\\").replace('"', '\\"'),
        "",
        "static const uint8_t ui_font_data[] = {",
    ]
    for ch in ORDER:
        b = to_bytes(GLYPHS[ch])
        lines.append("    " + ", ".join("0x%02X" % x for x in b) + ",  /* %s */" % (ch if ch != " " else "sp"))
    lines.append("};")
    lines.append("")
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print("wrote", path)


def write_png(path, scale=6):
    cols = len(ORDER)
    w = cols * (COLS + 1) * scale
    h = ROWS * scale
    px = [[(0, 0, 0) for _ in range(w)] for _ in range(h)]
    for i, ch in enumerate(ORDER):
        rows = GLYPHS[ch]
        for r in range(ROWS):
            for c in range(COLS):
                if rows[r][c] == "#":
                    for dy in range(scale):
                        for dx in range(scale):
                            x = (i * (COLS + 1) + c) * scale + dx
                            y = r * scale + dy
                            px[y][x] = (240, 240, 240)
    raw = b"".join(b"\x00" + b"".join(struct.pack("BBB", *p) for p in row) for row in px)
    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9))
    png += chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(png)
    print("wrote", path)


